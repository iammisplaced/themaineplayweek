-- One row per theatre and film, holding that theatre's ticket link for the film.
create table if not exists public.theatre_films (
  theatre_id bigint not null references public.theatres(id) on delete cascade,
  film_id bigint not null references public.films(id) on delete cascade,
  ticket_link text not null default '',
  created_at timestamptz not null default now(),
  primary key (theatre_id, film_id)
);

-- One row per showtime. show_date and start_time are local (America/New_York);
-- starts_at is the same moment as a timestamp.
create table if not exists public.showtimes (
  id bigint generated by default as identity primary key,
  theatre_id bigint not null references public.theatres(id) on delete cascade,
  film_id bigint not null references public.films(id) on delete cascade,
  festival_id bigint references public.festivals(id) on delete set null,
  show_date date not null,
  start_time time not null,
  starts_at timestamptz not null,
  is_premium boolean not null default false,
  format text,
  note text,
  room text,
  created_at timestamptz not null default now(),
  unique (theatre_id, film_id, starts_at, is_premium)
);

