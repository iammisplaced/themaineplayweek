returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if coalesce(current_setting('showtimes.in_full_save', true), '') = 'on' then
    return null;
  end if;
  update data_version set version = version + 1, changed_at = now() where id = 1;
  return null;
end;
$$;
