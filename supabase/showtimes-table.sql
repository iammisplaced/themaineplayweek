-- Step 4, phase A: adds the `showtimes` table (one row per showtime) next to `showings`
-- (one row per theatre, film and day with text time arrays). Run against one schema:
--   psql "$DATABASE_URL" -v schema=staging -f supabase/showtimes-table.sql
--
-- During phases A and B each showtime keeps a `showing_id`: inserting a showing adds
-- its showtimes (trigger below) and deleting it deletes them (foreign key), so every
-- admin save keeps both tables in step without changing replace_showtimes_data.
-- Phase C will write showtimes directly and drop `showings` and `showing_id`.
--
-- The parsing matches `to24HourTime` and `getShowtimeNote` in js/shared.js (checked
-- against all 2,623 staging showtimes on 2026-10-20).
--
-- Only adds things, so the current site keeps reading `showings` unaffected.

\set ON_ERROR_STOP on

begin;

-- Replaces the read-only view of the same name (staging only).
drop view if exists :"schema".showtimes;

-- "7:00 PM", "7pm", "7:00 p.m." or "19:00" -> 19:00. Null if it can't be read.
create or replace function :"schema".parse_show_time(value text)
returns time
language sql
immutable
set search_path = :'schema'
as $$
  select case
    when m24 is not null and m24[1]::int between 0 and 23
      then make_time(m24[1]::int, m24[2]::int, 0)
    when m12 is not null and m12[1]::int between 1 and 12
      then make_time(m12[1]::int % 12 + case when upper(m12[3]) = 'PM' then 12 else 0 end, coalesce(m12[2], '0')::int, 0)
  end
  from (
    select
      regexp_match(v, '^(\d{1,2}):([0-5]\d)$') as m24,
      regexp_match(v, '^(\d{1,2})(?::([0-5]\d))?\s*(AM|PM)$', 'i') as m12
    from (select regexp_replace(replace(btrim(coalesce(value, '')), '.', ''), '\s+', ' ', 'g') as v) cleaned
  ) matched
$$;

-- The part of a showing's note for one time: entries prefixed with that time
-- ("7:00 PM: Q&A") plus entries with no time prefix, joined with " · ". Null if none.
create or replace function :"schema".note_for_time(notes text, show_time time)
returns text
language sql
immutable
set search_path = :'schema'
as $$
  select nullif(string_agg(part, ' · ' order by ord), '')
  from (
    select
      ord,
      case
        when timed is null then segment
        when parse_show_time(timed[1]) = show_time then btrim(timed[2])
      end as part
    from regexp_split_to_table(
      coalesce(notes, ''),
      ';\s*(?=\d{1,2}(?::[0-5]\d)?\s*[ap]\.?m\.?\s*[:–—-]\s*)',
      'i'
    ) with ordinality as split(raw_segment, ord)
    cross join lateral (select btrim(raw_segment) as segment) trimmed
    cross join lateral (
      select regexp_match(segment, '^(\d{1,2}(?::[0-5]\d)?\s*[ap]\.?m\.?)\s*[:–—-]\s*(.+)$', 'i') as timed
    ) matched
    where segment <> ''
  ) parts
  where part is not null and part <> ''
$$;

-- The premium format named in a note, in the scrapers' spelling ("3-D" counts as 3D).
-- Screen formats win over 3D, so "IMAX 3D" is IMAX. Null if none.
create or replace function :"schema".format_from_note(note text)
returns text
language sql
immutable
set search_path = :'schema'
as $$
  select format
  from (values
    (1, 'IMAX', 'IMAX'),
    (2, 'ACX', 'ACX'),
    (3, 'ScreenX', 'ScreenX'),
    (4, 'FPX', 'FPX'),
    (5, '4K Laser', '4K Laser'),
    (6, 'RPX', 'RPX'),
    (7, '4DX', '4DX'),
    (8, '3D', '3-?D')
  ) as known(ord, format, pattern)
  where coalesce(note, '') ~* ('(^|[^[:alnum:]])' || pattern || '($|[^[:alnum:]])')
  order by ord
  limit 1
$$;

create table :"schema".showtimes (
  id bigint generated by default as identity primary key,
  showing_id bigint references :"schema".showings(id) on delete cascade,
  theatre_id bigint not null references :"schema".theatres(id) on delete cascade,
  film_id bigint not null references :"schema".films(id) on delete cascade,
  festival_id bigint references :"schema".festivals(id) on delete set null,
  show_date date not null,
  start_time time not null,
  starts_at timestamptz not null,
  is_premium boolean not null default false,
  format text,
  note text,
  room text,
  created_at timestamptz not null default now(),
  unique (theatre_id, film_id, starts_at, is_premium)
);

create index on :"schema".showtimes (starts_at);
create index on :"schema".showtimes (film_id, starts_at);
create index on :"schema".showtimes (theatre_id, starts_at);
create index on :"schema".showtimes (showing_id);

-- One showing's showtimes. Times that can't be read are skipped, as the site does.
create or replace function :"schema".insert_showtimes_for_showing(s :"schema".showings)
returns void
language sql
set search_path = :'schema'
as $$
  insert into showtimes (showing_id, theatre_id, film_id, festival_id, show_date, start_time, starts_at, is_premium, format, note, room)
  select
    s.id,
    s.theatre_id,
    s.film_id,
    s.festival_id,
    s.show_date,
    t.start_time,
    (s.show_date + t.start_time) at time zone 'America/New_York',
    t.is_premium,
    case when t.is_premium then coalesce(format_from_note(n.note), 'Premium') end,
    n.note,
    nullif(btrim(s.room), '')
  from (
    select distinct on (start_time, is_premium) start_time, is_premium
    from (
      select parse_show_time(raw) as start_time, false as is_premium from unnest(s.times) as raw
      union all
      select parse_show_time(raw), true from unnest(s.premium_times) as raw
    ) parsed
    where start_time is not null
  ) t
  cross join lateral (
    select case when btrim(s.notes) <> '' then note_for_time(s.notes, t.start_time) end as note
  ) n
  on conflict (theatre_id, film_id, starts_at, is_premium) do nothing
$$;

create or replace function :"schema".sync_showtimes_from_showing()
returns trigger
language plpgsql
set search_path = :'schema'
as $$
begin
  if tg_op = 'UPDATE' then
    delete from showtimes where showing_id = old.id;
  end if;
  perform insert_showtimes_for_showing(new);
  return null;
end;
$$;

create trigger trg_sync_showtimes
  after insert or update on :"schema".showings
  for each row execute function :"schema".sync_showtimes_from_showing();

-- Fill from the showings already saved.
select :"schema".insert_showtimes_for_showing(s) from :"schema".showings s;

-- The theatre's ticket link for the film, as a column the API can select
-- (`select=*,ticket_url`), so the app gets it with each showtime.
create or replace function :"schema".ticket_url(s :"schema".showtimes)
returns text
language sql
stable
set search_path = :'schema'
as $$
  select nullif(btrim(tf.ticket_link), '')
  from theatre_films tf
  where tf.theatre_id = s.theatre_id and tf.film_id = s.film_id
$$;

alter table :"schema".showtimes enable row level security;
create policy "Public read showtimes" on :"schema".showtimes for select using (true);
create policy "Auth write showtimes" on :"schema".showtimes for all to authenticated using (true) with check (true);
grant select on :"schema".showtimes to anon;
grant all on :"schema".showtimes to authenticated, service_role;
grant execute on function
  :"schema".parse_show_time(text),
  :"schema".note_for_time(text, time),
  :"schema".format_from_note(text),
  :"schema".ticket_url(:"schema".showtimes)
  to anon, authenticated, service_role;
revoke all on function :"schema".insert_showtimes_for_showing(:"schema".showings) from public;
revoke all on function :"schema".sync_showtimes_from_showing() from public;

create trigger trg_bump_data_version
  after insert or update or delete on :"schema".showtimes
  for each statement execute function :"schema".bump_data_version();

commit;
